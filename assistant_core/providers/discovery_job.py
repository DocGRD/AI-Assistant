"""
Discovery job — Milestone 16.7.

The reusable core of `vault:discover-providers`: query every registered provider's live
`/models`, build a PROPOSED registry (chat models capability-tagged + a second table of
specialized/non-chat models), and write it to `AI/System/Provider-Registry-proposed.md`
between the tracker's BEGIN/END markers. It never commits — `vault:update-providers
apply` does that (propose/commit). Shared by the terminal command and the weekly
scheduler so both produce an identical, review-first proposal.
"""

from __future__ import annotations

import logging
from pathlib import Path

logger = logging.getLogger("assistant")


def _status_counts(md: str) -> dict[str, int]:
    """Count chat statuses and specialized rows in a proposed registry."""
    chat, _, nonchat = md.partition("## Specialized")
    counts = {"active": 0, "candidate": 0, "deprecated": 0, "specialized": 0}
    for line in chat.splitlines():
        if not line.startswith("|") or line.startswith("| provider") or line.startswith("|---"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) >= 10 and cells[9] in ("active", "candidate", "deprecated"):
            counts[cells[9]] += 1
    for line in nonchat.splitlines():
        if line.startswith("|") and not line.startswith("| provider") and not line.startswith("|---"):
            counts["specialized"] += 1
    return counts


def format_discovery_summary(discovered: dict, md: str, probed: int,
                             provider_errors: list[str], written_rel: str) -> str:
    """Human-readable reply after a discovery run."""
    found = sum(len(info.get("models") or []) for info in discovered.values() if not info.get("error"))
    counts = _status_counts(md)
    list_errors = [name for name, info in discovered.items() if info.get("error")]
    errors = list(dict.fromkeys([*provider_errors, *list_errors]))
    err_txt = "none" if not errors else ", ".join(errors)
    active_label = "active (probe OK)" if probed else "active"
    lines = [
        f"Discovered {found} models. Probed {probed}.",
        f"  {active_label}: {counts['active']}",
        f"  candidate (unprobed or failed): {counts['candidate']}",
        f"  specialized: {counts['specialized']}",
    ]
    if counts["deprecated"]:
        lines.append(f"  deprecated (probe not found): {counts['deprecated']}")
    lines.append(f"  provider errors: {err_txt}")
    lines.append(f"Wrote {written_rel}")
    return "\n".join(lines)


def run_discovery_proposal(vault_path, config: dict, list_fn=None, probe_fn=None,
                           probe: bool | None = None) -> tuple[bool, str]:
    """Build and write the discovery proposal. Returns (ok, message).

    `list_fn` is injectable for tests (defaults to the live /models query).
    `probe_fn(base_url, api_key, model_id)` is injectable for the completion probe.
    `probe` overrides `discovery_probe_enabled` (default on). The weekly scheduler
    passes probe=False unless `discovery_probe_on_schedule` is set, so a night run
    does not spend free-tier completions. Writes nothing and returns (False, reason)
    if there is no vault or no providers."""
    from assistant_core.providers.model_discovery import discover_models
    from assistant_core.providers.model_probe import run_probes
    from assistant_core.providers.registry_loader import RegistryLoader
    from assistant_core.providers.registry_proposer import (
        build_proposed_registry, iter_discovered_rows,
    )
    from assistant_core.tools.provider_tracker import PROPOSED_REL, BEGIN_MARK, END_MARK

    if not vault_path:
        return False, "no vault_path"

    reg_path = Path(vault_path) / "AI" / "System" / "Provider-Registry.md"
    specs = RegistryLoader(reg_path).load() if reg_path.exists() else []
    providers: dict[str, str] = {}
    base_urls: dict[str, str] = {}
    for s in specs:
        providers.setdefault(s.provider, s.base_url)
        base_urls.setdefault(s.provider, s.base_url)
    if not providers:
        return False, "no providers in the registry yet"

    disc = discover_models(providers, config, list_fn=list_fn)
    do_probe = bool(config.get("discovery_probe_enabled", True)) if probe is None else bool(probe)
    probe_run_results = {}
    provider_errors: list[str] = []
    probed = 0
    if do_probe:
        rows = iter_discovered_rows(disc, specs)
        probe_run = run_probes(rows, base_urls, config, probe_fn=probe_fn)
        probe_run_results = probe_run.results
        provider_errors = probe_run.provider_errors
        probed = probe_run.probed
    registry_md = build_proposed_registry(
        disc, specs, base_urls, probe_results=probe_run_results, probe_config=config,
    )
    note = ("# Provider Registry — discovery proposal\n\n"
            "Generated by provider discovery. Review, then run "
            "`vault:update-providers apply` to commit (or delete this file to reject).\n\n"
            f"{BEGIN_MARK}\n{registry_md}\n{END_MARK}\n")

    out_path = Path(vault_path) / PROPOSED_REL
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(note, encoding="utf-8")

    msg = format_discovery_summary(disc, registry_md, probed, provider_errors, PROPOSED_REL)
    logger.info("[Discovery] %s", msg.replace("\n", " | "))
    return True, msg
